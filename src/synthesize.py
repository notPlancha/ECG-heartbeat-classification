"""
synthesize.py
=============
MAX78002 Software Synthesis and C Code Generation Tool for CRISP-DM Stage 6.

Translates the quantized INT8 1D CNN model into hardware-ready synthesis outputs
targeting the Analog Devices MAX78002 Edge-AI microcontroller.

Generates:
    - max78002/model_configuration/cnn_max78002.yaml (ai8x-synthesis network configuration)
    - max78002/synthesis_output/weights.h (C static const arrays of INT8 weights and INT32 biases)
    - max78002/synthesis_output/sample_input.h (C static const INT8 input test heartbeat)
    - max78002/synthesis_output/cnn.h & cnn.c (MAX78002 accelerator driver routines)
    - max78002/synthesis_output/main.c (Cortex-M4 application firmware entry point)
    - max78002/synthesis_output/synthesis_report.json & memory_budget.txt (Table 6.3 evidence)
"""

