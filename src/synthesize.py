def main() -> None:
    print("=" * 80)
    print("MAX78002 SOFTWARE SYNTHESIS AND EMBEDDED C CODE GENERATION (CRISP-DM Stage 6)")
    print("=" * 80)

    # 1. Model Configuration
    cfg_path = generate_model_configuration(DEFAULT_CONFIG_DIR)
    print(f"[Artifact Saved] Hardware Model Configuration -> {cfg_path}")

    # 2. Load Quantized Model
    if not DEFAULT_QUANT_PATH.exists():
        raise FileNotFoundError(f"Quantized weights not found at {DEFAULT_QUANT_PATH}. Run 'python src/quantize.py' first.")
    quant_data = np.load(DEFAULT_QUANT_PATH)

    # 3. Generate C code & Headers
    DEFAULT_SYNTH_DIR.mkdir(parents=True, exist_ok=True)
    generate_c_weights_header(quant_data, DEFAULT_SYNTH_DIR / "weights.h")
    print(f"[Artifact Saved] Embedded INT8 weights header -> {DEFAULT_SYNTH_DIR / 'weights.h'}")

    generate_sample_input_header(DEFAULT_TEST_PATH, float(quant_data["input_scale"]), DEFAULT_SYNTH_DIR / "sample_input.h")
    print(f"[Artifact Saved] Sample test heartbeat header -> {DEFAULT_SYNTH_DIR / 'sample_input.h'}")

    generate_c_driver_files(DEFAULT_SYNTH_DIR)
    print(f"[Artifact Saved] C driver and firmware source -> {DEFAULT_SYNTH_DIR / 'cnn.c'}, {DEFAULT_SYNTH_DIR / 'main.c'}")

    # 4. Generate Synthesis & Memory Budget Reports
    report = generate_synthesis_reports(quant_data, DEFAULT_SYNTH_DIR)
    print(f"[Artifact Saved] Synthesis JSON report -> {DEFAULT_SYNTH_DIR / 'synthesis_report.json'}")
    print(f"[Artifact Saved] Memory budget audit report -> {DEFAULT_SYNTH_DIR / 'memory_budget.txt'}")

    print("=" * 80)
    print("SYNTHESIS SUMMARY (Section 6.3 Compliance)")
    print("=" * 80)
    for k, v in report["results"].items():
        print(f"  {k:<35}: {v}")
    print(f"  Weight Memory: {report['memory_requirements']['weight_memory_required_bytes']:,} B ({report['memory_requirements']['weight_memory_utilization_percent']}% of 2.0 MB CRAM)")
    print(f"  Data Memory  : {report['memory_requirements']['activation_memory_required_bytes']:,} B ({report['memory_requirements']['activation_memory_utilization_percent']}% of 512 KB SRAM)")
    print(f"  Total MACs   : {report['computational_complexity']['total_mac_operations']:,} ops (~{report['computational_complexity']['estimated_latency_ms']} ms latency)")
    print("=" * 80)


if __name__ == "__main__":
    main()
