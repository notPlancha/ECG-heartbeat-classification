"""
train.py
========
Training pipeline for ECG heartbeat classification models.

Supports training the LogisticRegression baseline with either:
1. The classmates' raw data loader from ml-model/data_loader.py
2. The preprocessed .npz splits generated by src/prepare_data.py
"""

import argparse
import os
import sys
from pathlib import Path

import torch
from torch import nn
from torch.utils.data import DataLoader, TensorDataset

# Add workspace root to sys.path
PROJECT_ROOT = Path(__file__).resolve().parent.parent
if str(PROJECT_ROOT) not in sys.path:
  sys.path.insert(0, str(PROJECT_ROOT))

# Add ml-model directory to sys.path for importing their loader
ML_MODEL_DIR = PROJECT_ROOT / "ml-model"
if str(ML_MODEL_DIR) not in sys.path:
  sys.path.insert(0, str(ML_MODEL_DIR))

from src.constants import NUM_CLASSES, WINDOW_SIZE
from src.model import LogisticRegression


def calculate_class_weights(
  labels: torch.Tensor, num_classes: int = NUM_CLASSES
) -> torch.Tensor:
  """
  Calculate inverse-frequency class weights for cross-entropy loss.
  """
  labels_flat = torch.as_tensor(labels, dtype=torch.long).reshape(-1)
  counts = torch.bincount(labels_flat, minlength=num_classes).float()

  # Avoid division by zero if a class has no instances
  counts = torch.clamp(counts, min=1.0)
  total = counts.sum()
  return total / (num_classes * counts)


def load_data_from_classmates(
  quick_test: bool = False,
) -> tuple[DataLoader, DataLoader, torch.Tensor]:
  """
  Load raw training and test data using the classmates' data loader implementation.
  """
  from data_loader import _load_records, load_testing_data, load_training_data

  if quick_test:
    # Use only two records to verify the pipeline quickly
    print("Quick test mode: loading sample records 101 and 100...")
    X_train, y_train = _load_records(["101"])
    X_test, y_test = _load_records(["100"])
  else:
    print("Loading full training data from raw WFDB records...")
    X_train, y_train = load_training_data()
    print("Loading full test data from raw WFDB records...")
    X_test, y_test = load_testing_data()

  # Convert arrays to PyTorch tensors
  X_train_t = torch.tensor(X_train, dtype=torch.float32)
  y_train_t = torch.tensor(y_train, dtype=torch.long)
  X_test_t = torch.tensor(X_test, dtype=torch.float32)
  y_test_t = torch.tensor(y_test, dtype=torch.long)

  class_weights = calculate_class_weights(y_train_t, NUM_CLASSES)

  train_ds = TensorDataset(X_train_t, y_train_t)
  test_ds = TensorDataset(X_test_t, y_test_t)

  train_loader = DataLoader(train_ds, batch_size=64, shuffle=True)
  test_loader = DataLoader(test_ds, batch_size=64, shuffle=False)

  return train_loader, test_loader, class_weights


def train_one_epoch(
  model: nn.Module,
  loader: DataLoader,
  criterion: nn.Module,
  optimizer: torch.optim.Optimizer,
  device: torch.device,
) -> tuple[float, float]:
  """
  Execute one training epoch over batches.
  """
  model.train()
  total_loss = 0.0
  correct = 0
  total_samples = 0

  for beats, labels in loader:
    beats = beats.to(device)
    labels = labels.to(device)

    optimizer.zero_grad()
    logits = model(beats)
    loss = criterion(logits, labels)

    loss.backward()
    optimizer.step()

    batch_size = labels.size(0)
    total_loss += loss.item() * batch_size
    preds = logits.argmax(dim=1)
    correct += (preds == labels).sum().item()
    total_samples += batch_size

  avg_loss = total_loss / max(total_samples, 1)
  accuracy = 100.0 * correct / max(total_samples, 1)
  return avg_loss, accuracy


@torch.no_grad()
def evaluate(
  model: nn.Module,
  loader: DataLoader,
  criterion: nn.Module,
  device: torch.device,
) -> tuple[float, float]:
  """
  Evaluate model performance across batches without tracking gradients.
  """
  model.eval()
  total_loss = 0.0
  correct = 0
  total_samples = 0

  for beats, labels in loader:
    beats = beats.to(device)
    labels = labels.to(device)

    logits = model(beats)
    loss = criterion(logits, labels)

    batch_size = labels.size(0)
    total_loss += loss.item() * batch_size
    preds = logits.argmax(dim=1)
    correct += (preds == labels).sum().item()
    total_samples += batch_size

  avg_loss = total_loss / max(total_samples, 1)
  accuracy = 100.0 * correct / max(total_samples, 1)
  return avg_loss, accuracy


def run_training(
  loader_type: str = "classmates",
  epochs: int = 20,
  lr: float = 0.001,
  batch_size: int = 64,
  quick_test: bool = False,
  save_path: str = "results/logistic_regression.pt",
) -> None:
  """
  Run the complete training workflow.
  """
  device = torch.device("cuda" if torch.cuda.is_available() else "cpu")
  print(f"Using device: {device}")

  if loader_type == "classmates":
    print("Using classmates data loading solution (ml-model/data_loader.py)...")
    train_loader, val_loader, class_weights = load_data_from_classmates(
      quick_test=quick_test
    )
  else:
    raise NotImplementedError(
      f"Loader type '{loader_type}' is reserved for subsequent integration iterations."
    )

  model = LogisticRegression(in_features=WINDOW_SIZE, num_classes=NUM_CLASSES)
  model = model.to(device)

  class_weights = class_weights.to(device)
  criterion = nn.CrossEntropyLoss(weight=class_weights)
  optimizer = torch.optim.SGD(model.parameters(), lr=lr)

  print(f"Model parameters: {sum(p.numel() for p in model.parameters())}")
  print(f"Class weights: {[round(w, 4) for w in class_weights.tolist()]}")
  print("-" * 65)

  best_val_acc = 0.0

  for epoch in range(1, epochs + 1):
    train_loss, train_acc = train_one_epoch(
      model, train_loader, criterion, optimizer, device
    )
    val_loss, val_acc = evaluate(model, val_loader, criterion, device)

    print(
      f"Epoch {epoch:2d}/{epochs:2d} | "
      f"Train Loss: {train_loss:.4f} | Train Acc: {train_acc:.2f}% | "
      f"Val Loss: {val_loss:.4f} | Val Acc: {val_acc:.2f}%"
    )

    if val_acc > best_val_acc:
      best_val_acc = val_acc
      os.makedirs(os.path.dirname(save_path), exist_ok=True)
      torch.save(model.state_dict(), save_path)

  print("-" * 65)
  print(f"Training completed. Best validation accuracy: {best_val_acc:.2f}%")
  print(f"Saved model checkpoint to: {save_path}")


def main() -> None:
  parser = argparse.ArgumentParser(
    description="Train LogisticRegression baseline for ECG classification."
  )
  parser.add_argument(
    "--loader",
    type=str,
    choices=["classmates", "npz"],
    default="classmates",
    help="Data loader source to use (default: classmates).",
  )
  parser.add_argument(
    "--epochs",
    type=int,
    default=10,
    help="Number of training epochs (default: 10).",
  )
  parser.add_argument(
    "--lr",
    type=float,
    default=0.001,
    help="Learning rate for SGD optimizer (default: 0.001).",
  )
  parser.add_argument(
    "--batch-size",
    type=int,
    default=64,
    help="Batch size for training and evaluation (default: 64).",
  )
  parser.add_argument(
    "--quick-test",
    action="store_true",
    help="Run quick sanity check on a small subset of records.",
  )
  parser.add_argument(
    "--save-path",
    type=str,
    default="results/logistic_regression.pt",
    help="Path to save the best model weights.",
  )
  args = parser.parse_args()

  run_training(
    loader_type=args.loader,
    epochs=args.epochs,
    lr=args.lr,
    batch_size=args.batch_size,
    quick_test=args.quick_test,
    save_path=args.save_path,
  )


if __name__ == "__main__":
  main()
